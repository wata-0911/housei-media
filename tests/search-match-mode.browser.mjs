import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLANNER_PLAYWRIGHT_MODULE || 'playwright');
import { catalog } from '../src/planner/catalog/catalog.ts';
import { searchOfferings } from '../src/planner/calculations.ts';
import { filterOfferingsByYear } from '../src/planner/planning/yearEligibility.ts';
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [1280, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    await page.goto('http://127.0.0.1:4194/planner');
    await page.getByRole('tab', { name: '年間履修計画', exact: true }).click();
    const section = page.locator('section').filter({ has: page.getByRole('heading', { name: '科目を探す', exact: true }) });
    await section.waitFor();
    const query = page.locator('#course-query');
    const exact = page.getByRole('radio', { name: '完全一致', exact: true });
    const partial = page.getByRole('radio', { name: '部分一致', exact: true });
    const rows = section.getByRole('list', { name: '検索結果' }).locator(':scope > li');
    assert.equal(await partial.isChecked(), true);
    await section.getByRole('button', { name: 'さらに30件表示' }).click();
    assert.equal(await rows.count(), 60);
    await partial.focus(); await page.keyboard.press('ArrowRight');
    assert.equal(await exact.isChecked(), true);
    assert.equal(await rows.count(), 30);
    await query.fill('簿記');
    const expected = searchOfferings(catalog.offerings, '簿記', 'exact');
    assert.equal(await rows.count(), expected.length);
    assert.equal(expected.length, 0);
    for (const title of await rows.locator('h3').allTextContents()) assert.equal(title, '簿記');
    await page.waitForTimeout(700);
    const saved = await page.evaluate(() => JSON.stringify(localStorage));
    await partial.check();
    assert.equal(await query.inputValue(), '簿記');
    assert.equal(await rows.count(), searchOfferings(catalog.offerings, '簿記').length);
    await query.fill('簿記Ⅰ');
    await exact.check();
    const named = searchOfferings(catalog.offerings, '簿記Ⅰ', 'exact');
    assert.ok(named.length > 0);
    assert.equal(await rows.count(), named.length);
    await section.getByRole('combobox').selectOption('1');
    const eligible = filterOfferingsByYear(named, null, 1, false, catalog);
    assert.equal(await rows.count(), eligible.length);
    await section.getByRole('checkbox').check();
    assert.equal(await rows.count(), filterOfferingsByYear(named, null, 1, true, catalog).length);
    await section.getByRole('combobox').selectOption('');
    await query.fill('不存在科目'); assert.equal(await rows.count(), 0);
    await query.fill('　 '); assert.equal(await rows.count(), 30);
    await query.fill('公開'); assert.equal(await rows.count(), 0);
    await query.fill('公開科目');
    assert.equal(await section.getByRole('button', { name: '公開科目を履修計画に追加' }).count(), 1);
    await partial.check(); await query.fill('公開');
    assert.equal(await section.getByRole('button', { name: '公開科目を履修計画に追加' }).count(), 1);
    await query.fill('簿記'); await exact.check();
    await page.waitForTimeout(700);
    assert.equal(await page.evaluate(() => JSON.stringify(localStorage)), saved);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await section.screenshot({ path: `verification/search-${width}.png` });
    console.log(`PASS ${width}px: radio keyboard, counts, pagination, year/unknown filters, public course, unchanged storage, no overflow`);
    await page.close();
  }
} finally { await browser.close(); }
