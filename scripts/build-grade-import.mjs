import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const bundle = async (entry, minify) => {
  const result = await build({
    absWorkingDir: root, entryPoints: [entry], bundle: true, write: false,
    format: 'iife', platform: 'browser', target: 'es2020', minify,
    charset: 'ascii', legalComments: 'none', sourcemap: false,
  });
  return result.outputFiles[0].text;
};
const extension = `/* Generated by npm run build:grade-import. Edit shared/grade-import/extractor.js instead. */\n${await bundle('extension/hosei-planner-import/parser/entry.js', false)}`;
// URI encoding prevents URL fragment/percent/newline interpretation in bookmark editors.
// The explicit void wrapper prevents javascript: navigation from replacing the page.
const code = await bundle('bookmarklet/entry.js', true);
const bookmarklet = `javascript:${encodeURIComponent(`void(()=>{${code.trim()}})()`)}`;
const artifacts = [
  ['extension/hosei-planner-import/parser/extractor.js', extension],
  ['src/generated/gradeImportBookmarklet.json', `${JSON.stringify({ bookmarklet }, null, 2)}\n`],
];
for (const [relative, expected] of artifacts) {
  const path = `${root}/${relative}`;
  if (check) {
    const actual = await readFile(path, 'utf8').catch(() => '');
    if (actual !== expected) throw new Error(`${relative} is stale. Run npm run build:grade-import.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, expected);
  }
}
console.log(`${check ? 'Verified' : 'Generated'} grade import artifacts; bookmarklet ${Buffer.byteLength(bookmarklet)} bytes (${bookmarklet.length} characters).`);
